package io.github.hyperprivacy.core.rule

/** An app version, as recorded by the survey the catalog evidence comes from. */
public data class VersionPin(val versionCode: Long, val versionName: String?)

/**
 * The build a device runs, as reported by `android.os.Build`; passed in so health logic stays pure.
 *
 * @property model `Build.MODEL` (model number).
 * @property device `Build.DEVICE` (codename, e.g. `nezha`).
 * @property incremental `Build.VERSION.INCREMENTAL` (ROM build, e.g. `OS4.0.5.0.XPACNXM`).
 */
public data class DeviceBuild(val model: String, val device: String, val incremental: String)

/** The device and ROM build a [Baseline] survey was taken on. */
public data class SurveyedDevice(val codename: String, val incremental: String) {
    /** Same device (codename as `Build.DEVICE` or `Build.MODEL`, any case) and exactly the same ROM build. */
    public fun matches(build: DeviceBuild): Boolean {
        val sameDevice = build.device.equals(codename, ignoreCase = true) ||
            build.model.equals(codename, ignoreCase = true)
        return sameDevice && build.incremental == incremental
    }
}

/**
 * Versions of the vendor apps at the time the catalog evidence was gathered. A target whose
 * installed version differs from its pin may have changed the interface a rule relies on, so the
 * rule deserves a review (see `core.health.RuleHealth`).
 *
 * The data lives in [BaselineData], regenerated by `scripts/gen-baseline.py` after a re-survey.
 * It is parsed lazily on first use; malformed rows are skipped.
 *
 * The pins only mean something on the surveyed [device]: other models and ROM builds ship other
 * versions of nearly every app, so health falls back to device-local history there.
 */
public object Baseline {
    private const val FIELD_COUNT = 3
    private const val UNKNOWN_NAME = "-"

    /** Where the survey behind [BaselineData] was taken. Update together with the table after a re-survey. */
    public val device: SurveyedDevice = SurveyedDevice(codename = "nezha", incremental = "OS4.0.5.0.XPACNXM")

    /** Whether [build] is the surveyed device and ROM build, so the pins apply to it. */
    public fun isSurveyed(build: DeviceBuild): Boolean = device.matches(build)

    private val pins: Map<String, VersionPin> by lazy { parse(BaselineData.TABLE) }

    /** Every package with a recorded version. */
    public val packages: Set<String> get() = pins.keys

    /** The surveyed version of [packageName], or `null` if it was not surveyed. */
    public fun of(packageName: String): VersionPin? = pins[packageName]

    internal fun parse(table: String): Map<String, VersionPin> = table.lineSequence()
        .mapNotNull { line ->
            val fields = line.trim().split(' ').takeIf { it.size == FIELD_COUNT } ?: return@mapNotNull null
            val code = fields[1].toLongOrNull()?.takeIf { it >= 0 } ?: return@mapNotNull null
            fields[0] to VersionPin(code, fields[2].takeIf { it != UNKNOWN_NAME })
        }
        .toMap()
}
