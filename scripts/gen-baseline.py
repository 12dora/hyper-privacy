#!/usr/bin/env python3
"""Regenerates core/.../rule/BaselineData.kt from a device version survey.

Usage: scripts/gen-baseline.py <versions.json>

The JSON maps package name -> {"versionCode": int, "versionName": str}, as collected when the
catalog evidence was gathered. Only vendor packages (VENDOR_PATTERN) are kept, because the
catalog only ever targets those and the table must not list the user's own apps.
"""

import json
import re
import sys
from pathlib import Path

VENDOR_PATTERN = re.compile(
    r"^(com\.miui|com\.xiaomi|com\.mi\.|com\.android\.|com\.mobiletools|com\.baidu\.input|com\.sohu"
    r"|com\.iflytek|com\.milink|com\.lbe|com\.duokan|miui\.|com\.mfashion|com\.unionpay\.tsm|com\.fido)"
)
PACKAGE_PATTERN = re.compile(r"^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z][A-Za-z0-9_]*)+$")
# Version names go into a Kotlin raw string, space-separated: no whitespace, '$' or quotes.
NAME_PATTERN = re.compile(r"^[^\s$\"]+$")
# scripts/privacy-scan.sh flags private IPv4 addresses; a few version names look like one
# (four dotted numbers starting 10.x). Those names are dropped: only versionCode drives rule health.
PRIVATE_IPV4 = re.compile(
    r"\b(10\.[0-9]{1,3}|192\.168|172\.(1[6-9]|2[0-9]|3[01]))\.[0-9]{1,3}\.[0-9]{1,3}\b"
)
MAX_LINE = 120
UNKNOWN_NAME = "-"

OUTPUT = Path(__file__).resolve().parent.parent / (
    "core/src/main/kotlin/io/github/hyperprivacy/core/rule/BaselineData.kt"
)

HEADER = '''// Generated by scripts/gen-baseline.py from a device version survey. Do not edit by hand.
package io.github.hyperprivacy.core.rule

/**
 * Raw [Baseline] table: one `package versionCode versionName` row per line, space-separated,
 * sorted by package. `-` stands for a missing version name.
 */
internal object BaselineData {
    const val TABLE: String = """
'''

FOOTER = '''"""
}
'''


def rows(survey: dict) -> list[str]:
    out = []
    for package in sorted(survey):
        if not VENDOR_PATTERN.match(package):
            continue
        if not PACKAGE_PATTERN.match(package):
            sys.exit(f"invalid package name: {package!r}")
        entry = survey[package]
        code = entry.get("versionCode")
        if not isinstance(code, int) or code < 0:
            sys.exit(f"{package}: versionCode must be a non-negative integer")
        name = entry.get("versionName") or UNKNOWN_NAME
        if PRIVATE_IPV4.search(name):
            print(f"note: {package}: dropping IP-like versionName {name!r}", file=sys.stderr)
            name = UNKNOWN_NAME
        if not NAME_PATTERN.match(name):
            sys.exit(f"{package}: versionName {name!r} contains whitespace, '$' or quotes")
        line = f"{package} {code} {name}"
        if len(line) > MAX_LINE:
            sys.exit(f"{package}: row longer than {MAX_LINE} characters")
        out.append(line)
    return out


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with open(sys.argv[1], encoding="utf-8") as f:
        survey = json.load(f)
    if not isinstance(survey, dict):
        sys.exit("survey JSON must be an object keyed by package name")
    table = rows(survey)
    OUTPUT.write_text(HEADER + "\n".join(table) + "\n" + FOOTER, encoding="utf-8")
    print(f"wrote {len(table)} packages to {OUTPUT.name}")
    print("remember: update Baseline.device (codename, ROM incremental) to the surveyed device")


if __name__ == "__main__":
    main()
