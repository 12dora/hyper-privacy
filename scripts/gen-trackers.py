#!/usr/bin/env python3
"""Regenerates core/.../tracker/TrackerData.kt from data/trackers.json.

Usage: python3 -I scripts/gen-trackers.py [trackers.json]

The JSON is the tracker SDK signature database (schema 1): code prefixes that identify an SDK in
an app's dex, and the hosts / URL prefixes it reports to. Only what the app needs at runtime is
kept (names, optional display names, vendor, categories, defaultBlock, prefixes, hosts); evidence
and notes stay in the JSON. Output is deterministic: trackers sorted by id, list fields in source order.

The generated file also records SHA-256 digests of the source JSON and of the emitted table, so
TrackerDataTest notices a JSON change without a re-run, or a hand edit of the table, with no
Python in CI.
"""

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data/trackers.json"
OUTPUT = ROOT / "core/src/main/kotlin/io/github/hyperprivacy/core/tracker/TrackerData.kt"

SCHEMA = 1
CATEGORIES = {"ADS", "ANALYTICS", "CRASH", "IDENTIFICATION", "PROFILING", "LOCATION", "PUSH", "ATTRIBUTION"}
ID_PATTERN = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
PREFIX_PATTERN = re.compile(r"^[A-Za-z_][A-Za-z0-9_$]*(\.[A-Za-z0-9_$]+)*\.?$")
HOST_PATTERN = re.compile(r"^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$")
PATH_PATTERN = re.compile(r"^/[\x21-\x7e]+$")
# Text goes into a Kotlin raw string, one field per line.
TEXT_FORBIDDEN = re.compile(r"[\r\n$\"\x00-\x1f]")
MAX_LINE = 100
# Kotlin constant strings are limited to 65535 bytes of modified UTF-8; stay well below.
MAX_PART_BYTES = 30000

HEADER = '''// Generated by scripts/gen-trackers.py from data/trackers.json. Do not edit by hand.
package io.github.hyperprivacy.core.tracker

/**
 * Raw [Trackers] table, one record per SDK. A record starts with `sdk <id> <defaultBlock 1|0>
 * <CATEGORY,...>`; the following lines are `n` name (zh), `e` name (en), optional `dn` / `de`
 * display name (zh / en), `v` vendor, and the space-separated, repeatable lists `p` code
 * prefixes, `b` block hosts, `u` block URLs (`host/path`) and `k` keep hosts. Unknown tags are
 * ignored by the parser.
 */
internal object TrackerData {
    const val VERSION: String = "{version}"

    /** SHA-256 of data/trackers.json as generated. */
    const val SOURCE_SHA256: String = "{source_sha}"

    /** SHA-256 of [PARTS] joined, so a hand edit of the table is caught by tests. */
    const val TABLE_SHA256: String = "{table_sha}"

    val PARTS: List<String> = listOf({names})
}
'''


def fail(message: str) -> None:
    sys.exit(f"gen-trackers: {message}")


def text(tracker: dict, field: str) -> str:
    value = tracker.get(field)
    if not isinstance(value, str) or not value.strip():
        fail(f"{tracker.get('id')}: {field} must be a non-empty string")
    value = value.strip()
    if TEXT_FORBIDDEN.search(value):
        fail(f"{tracker['id']}: {field} contains a newline, '$', quote or control character")
    return value


def strings(tracker: dict, field: str, pattern: re.Pattern, required: bool = False) -> list:
    values = tracker.get(field, [])
    if not isinstance(values, list) or not all(isinstance(v, str) for v in values):
        fail(f"{tracker['id']}: {field} must be a list of strings")
    if required and not values:
        fail(f"{tracker['id']}: {field} must not be empty")
    for value in values:
        if not pattern.match(value):
            fail(f"{tracker['id']}: invalid {field} entry {value!r}")
    if len(set(values)) != len(values):
        fail(f"{tracker['id']}: duplicate {field} entries")
    return values


def urls(tracker: dict) -> list:
    out = []
    for entry in tracker.get("blockUrls", []):
        host, path = entry.get("host"), entry.get("pathPrefix")
        if not isinstance(host, str) or not HOST_PATTERN.match(host):
            fail(f"{tracker['id']}: invalid blockUrls host {host!r}")
        if not isinstance(path, str) or not PATH_PATTERN.match(path) or len(path) < 2:
            fail(f"{tracker['id']}: blockUrls pathPrefix must be a non-root path: {path!r}")
        out.append(host + path)
    return out


def wrapped(tag: str, values: list) -> list:
    """`tag v1 v2 ...` lines of at most MAX_LINE characters."""
    lines, current = [], tag
    for value in values:
        if len(tag) + 1 + len(value) > MAX_LINE:
            fail(f"value longer than a line: {value!r}")
        if current != tag and len(current) + 1 + len(value) > MAX_LINE:
            lines.append(current)
            current = tag
        current += " " + value
    if current != tag:
        lines.append(current)
    return lines


def record(tracker: dict) -> list:
    tid = tracker.get("id")
    if not isinstance(tid, str) or not ID_PATTERN.match(tid):
        fail(f"invalid id {tid!r}")
    categories = tracker.get("categories")
    if not isinstance(categories, list) or not categories or not set(categories) <= CATEGORIES:
        fail(f"{tid}: categories must be a non-empty subset of {sorted(CATEGORIES)}")
    if len(set(categories)) != len(categories):
        fail(f"{tid}: duplicate categories")
    default_block = tracker.get("defaultBlock", True)
    if not isinstance(default_block, bool):
        fail(f"{tid}: defaultBlock must be a boolean")
    if not tracker.get("evidence"):
        fail(f"{tid}: evidence must not be empty")
    lines = [f"sdk {tid} {1 if default_block else 0} {','.join(categories)}"]
    for tag, field in (("n", "name"), ("e", "nameEn"), ("v", "vendor")):
        line = f"{tag} {text(tracker, field)}"
        if len(line) > MAX_LINE:
            fail(f"{tid}: {field} longer than {MAX_LINE - 2} characters")
        lines.append(line)
    for tag, field in (("dn", "displayName"), ("de", "displayNameEn")):
        if field in tracker:
            line = f"{tag} {text(tracker, field)}"
            if len(line) > MAX_LINE:
                fail(f"{tid}: {field} longer than {MAX_LINE - 3} characters")
            lines.append(line)
    lines += wrapped("p", strings(tracker, "codePrefixes", PREFIX_PATTERN, required=True))
    lines += wrapped("b", strings(tracker, "blockHosts", HOST_PATTERN))
    lines += wrapped("u", urls(tracker))
    lines += wrapped("k", strings(tracker, "keepHosts", HOST_PATTERN))
    return lines


def parts(records: list) -> list:
    out, current = [], ""
    for lines in records:
        chunk = "\n".join(lines) + "\n"
        if current and len((current + chunk).encode("utf-8")) > MAX_PART_BYTES:
            out.append(current)
            current = ""
        current += chunk
    if current:
        out.append(current)
    return out


def main() -> None:
    if len(sys.argv) > 2:
        sys.exit(__doc__)
    source = Path(sys.argv[1]) if len(sys.argv) == 2 else SOURCE
    raw = source.read_bytes()
    data = json.loads(raw.decode("utf-8"))
    if data.get("schema") != SCHEMA:
        fail(f"unsupported schema {data.get('schema')!r}, expected {SCHEMA}")
    version = data.get("version")
    if not isinstance(version, str) or not re.match(r"^[0-9A-Za-z.\-]+$", version):
        fail("version must be a plain string")
    trackers = sorted(data.get("trackers", []), key=lambda t: t.get("id", ""))
    ids = [t.get("id") for t in trackers]
    if len(set(ids)) != len(ids):
        fail("duplicate tracker ids")
    table = parts([record(t) for t in trackers])
    source_sha = hashlib.sha256(raw).hexdigest()
    # Each Kotlin raw string starts with the newline after its opening quotes.
    table_sha = hashlib.sha256("".join("\n" + part for part in table).encode("utf-8")).hexdigest()
    names = ", ".join(f"PART_{i}" for i in range(len(table)))
    header = HEADER.replace("{version}", version).replace("{source_sha}", source_sha)
    body = [header.replace("{table_sha}", table_sha).replace("{names}", names)]
    # Top level, so the object stays small; each part is one Kotlin string constant.
    for index, part in enumerate(table):
        body.append(f'\nprivate const val PART_{index}: String = """\n{part}"""\n')
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("".join(body), encoding="utf-8")
    print(f"wrote {len(trackers)} trackers in {len(table)} parts to {OUTPUT.name}")


if __name__ == "__main__":
    main()
